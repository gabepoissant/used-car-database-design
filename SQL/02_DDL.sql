-- Create entities described by logical diagram
-- Establish data types and default values
-- Establish Primary Keys for each entity
-- Record 'Created_Date' and 'Modified_Date' 
CREATE TABLE MODEL_YEAR
(Model_Year_ID INT AUTO_INCREMENT,
Model_Year INT,
Created_Date DATETIME DEFAULT CURRENT_TIMESTAMP,
Modified_Date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT PK_MODEL_YEAR PRIMARY KEY (Model_Year_ID));

CREATE TABLE MAKE
(Make_ID INT AUTO_INCREMENT,
Make VARCHAR(50),
Created_Date DATETIME DEFAULT CURRENT_TIMESTAMP,
Modified_Date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT PK_MAKE PRIMARY KEY (Make_ID));

CREATE TABLE MODEL
(Model_ID INT AUTO_INCREMENT,
Model VARCHAR(50),
Created_Date DATETIME DEFAULT CURRENT_TIMESTAMP,
Modified_Date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT PK_MODEL PRIMARY KEY (Model_ID));

CREATE TABLE TRIM_TYPE
(Trim_Type_ID INT AUTO_INCREMENT,
Trim_Type VARCHAR(50),
Created_Date DATETIME DEFAULT CURRENT_TIMESTAMP,
Modified_Date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT PK_TRIM_TYPE PRIMARY KEY (Trim_Type_ID));

CREATE TABLE BODY
(Body_ID INT AUTO_INCREMENT,
