Created_Date DATETIME DEFAULT CURRENT_TIMESTAMP,
Modified_Date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT PK_TRANSMISSION PRIMARY KEY (Transmission_ID));

CREATE TABLE STATE
(State_ID INT AUTO_INCREMENT,
State VARCHAR(2),
Created_Date DATETIME DEFAULT CURRENT_TIMESTAMP,
Modified_Date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT PK_STATE PRIMARY KEY (State_ID));

CREATE TABLE COLOR
(Color_ID INT AUTO_INCREMENT,
Color VARCHAR(50),
Created_Date DATETIME DEFAULT CURRENT_TIMESTAMP,
Modified_Date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT PK_COLOR PRIMARY KEY (Color_ID));

CREATE TABLE SELLER
(Seller_ID INT AUTO_INCREMENT,
Seller VARCHAR(50) DEFAULT 'Unknown',
Created_Date DATETIME DEFAULT CURRENT_TIMESTAMP,
Modified_Date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT PK_SELLER PRIMARY KEY (Seller_ID));

CREATE TABLE CAR_SALE
(Sale_ID INT AUTO_INCREMENT,
VIN VARCHAR(50) NOT NULL,
Car_Condition VARCHAR(50),
Odometer INT,
MMR INT,
Selling_Price INT,
Sale_Date TIMESTAMP,
Model_Year_ID INT,
Make_ID INT, 
Model_ID INT, 
Trim_Type_ID INT,
Body_ID INT,
Transmission_ID INT,
State_ID INT,
Color_ID INT, 
Interior_Color_ID INT,
Seller_ID INT NOT NULL,
Created_Date DATETIME DEFAULT CURRENT_TIMESTAMP,
Modified_Date DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
CONSTRAINT PK_SALE PRIMARY KEY (Sale_ID));

